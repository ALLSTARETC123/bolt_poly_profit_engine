  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_withdrawal_requests" ON withdrawal_requests;
CREATE POLICY "anon_update_withdrawal_requests" ON withdrawal_requests FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_withdrawal_requests" ON withdrawal_requests;
CREATE POLICY "anon_delete_withdrawal_requests" ON withdrawal_requests FOR DELETE
  TO anon, authenticated USING (true);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_wallet_transactions_wallet ON wallet_transactions(wallet_address);
CREATE INDEX IF NOT EXISTS idx_wallet_transactions_created ON wallet_transactions(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_withdrawal_requests_status ON withdrawal_requests(status);
CREATE INDEX IF NOT EXISTS idx_withdrawal_requests_created ON withdrawal_requests(requested_at DESC);
